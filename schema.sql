CREATE TABLE IF NOT EXISTS users (
  email VARCHAR(254) PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  role ENUM('aluno','professor','resp','ti') NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  ra VARCHAR(32) UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS passwords (
  email VARCHAR(254) PRIMARY KEY,
  hash CHAR(161) NOT NULL,
  FOREIGN KEY (email) REFERENCES users(email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
  hash CHAR(64) PRIMARY KEY,
  email VARCHAR(254) NOT NULL,
  expires BIGINT NOT NULL,
  INDEX (expires),
  FOREIGN KEY (email) REFERENCES users(email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS limits (
  id VARCHAR(128) PRIMARY KEY,
  attempts INT UNSIGNED NOT NULL,
  expires BIGINT NOT NULL,
  INDEX (expires)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS materials (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(180) NOT NULL,
  cat VARCHAR(80) NOT NULL,
  un ENUM('un','m','rolo','pacote') NOT NULL,
  local VARCHAR(180) NOT NULL,
  qtd INT UNSIGNED NOT NULL,
  min INT UNSIGNED NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS stock_movements (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  material_id INT UNSIGNED NOT NULL,
  tipo ENUM('entrada','saida') NOT NULL,
  qtd INT UNSIGNED NOT NULL,
  obs VARCHAR(500) NOT NULL,
  actor VARCHAR(254) NOT NULL,
  reservation_code VARCHAR(32),
  em DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (material_id) REFERENCES materials(id),
  FOREIGN KEY (actor) REFERENCES users(email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS first_access (
  email VARCHAR(254) PRIMARY KEY,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires BIGINT NOT NULL,
  FOREIGN KEY (email) REFERENCES users(email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reservation_lock (
  id TINYINT PRIMARY KEY
) ENGINE=InnoDB;
INSERT IGNORE INTO reservation_lock VALUES (1);
CREATE TABLE IF NOT EXISTS reservations (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  owner VARCHAR(254) NOT NULL,
  requester_role ENUM('aluno','professor') NOT NULL,
  lab VARCHAR(8) NOT NULL,
  day CHAR(10) NOT NULL,
  slot VARCHAR(4) NOT NULL,
  status ENUM('pendente','aprovada','recusada','cancelada') NOT NULL DEFAULT 'pendente',
  details JSON NOT NULL,
  history JSON NOT NULL,
  created CHAR(24) NOT NULL,
  INDEX (owner, status, day),
  INDEX (lab, day, slot, status),
  FOREIGN KEY (owner) REFERENCES users(email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS reservation_attachments (
  reservation_id INT UNSIGNED PRIMARY KEY,
  filename VARCHAR(180) NOT NULL,
  content MEDIUMBLOB NOT NULL,
  FOREIGN KEY (reservation_id) REFERENCES reservations(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
